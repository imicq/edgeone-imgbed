// 把 EdgeOne 函数预打包成一个单文件（只导出 default，minify 掉所有内部命名导出）。
// 原因：EdgeOne 的函数运行时会扫描包内的 `onRequestGet` / `onRequestPost` 等 Pages 风格
// 命名导出，并直接按 HTTP 方法调用它们，从而绕过我们统一的路由分发逻辑。
import * as esbuild from 'esbuild';

const result = await esbuild.build({
  entryPoints: ['deploy/edgeone/bundle-entry.mjs'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: true,
  keepNames: false,
  charset: 'utf8',
  outfile: 'function-bundle.mjs',
  logLevel: 'error',
  banner: {
    js: '// AUTO-GENERATED by scripts/build-function.mjs — do not edit',
  },
});

if (result.errors.length) process.exit(1);
console.log('[build-function] function-bundle.mjs ok');
