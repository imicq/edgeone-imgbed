/**
 * 前端分片参数补丁（EdgeOne 1MB 请求体限制）
 *
 * CloudFlare-ImgBed 前端默认按 16MB 分片、20MB 以下整包直传。
 * EdgeOne 边缘函数的请求体上限是 1MB，必须在浏览器侧改小分片，否则 >1MB 的图会在进函数前被 413。
 *
 * 运行：node scripts/patch-frontend-edgeone.mjs
 * 幂等：重复执行不会破坏文件。
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const BUNDLE = join(ROOT, 'frontend-dist', 'js', '375.43b3c74e.js');

// 900000 字节 ≈ 0.86MB，给 multipart 字段与头部留出余量
const CHUNK_BYTES = '900000';

const PRELINK_OWNER_PATTERN = 'ownerName(){return this.configuredOwnerName||"Sanyue"},';
const PRELINK_TITLE_METHOD = 'titleHref(){return this.userConfig?.logoLink||""},';
const DUP_TITLE = PRELINK_TITLE_METHOD + PRELINK_TITLE_METHOD;

const REPLACEMENTS = [
    // 分片大小：discord 9MB / 其它 16MB -> 统一 900KB
    ['"discord"===o?9437184:16777216', `"discord"===o?${CHUNK_BYTES}:${CHUNK_BYTES}`],
    // 整包直传阈值：20MB -> 900KB（超过就走分片）
    ['const i=20971520;e.file.size>i', `const i=${CHUNK_BYTES};e.file.size>i`],
    // Logo 跳转：上游只有首页头部传了 useConfigLink，其余页面永远跳默认 GitHub。
    // 这里去掉 useConfigLink 限制，只要后台配置了 logoLink 就一律使用它。
    ['this.useConfigLink&&this.userConfig?.logoLink', 'this.userConfig?.logoLink'],
    // 首页中间「站名/作者名」链接：上游写死成 GitHub 仓库地址，这里改成读取后台
    // 配置的「Logo跳转链接」(logoLink)，未配置时回落到站点根路径。
    // 幂等：只在还没有 titleHref 时插一次
    [PRELINK_OWNER_PATTERN, PRELINK_OWNER_PATTERN + PRELINK_TITLE_METHOD],
    [
        '(0,l.Lk)("a",Oo,(0,n.v_)(d.ownerName),1)',
        '(0,l.Lk)("a",{class:"main-title",href:d.titleHref||"/",target:"_blank"},(0,n.v_)(d.ownerName),1)',
    ],
];

let source = readFileSync(BUNDLE, 'utf8');
let changed = 0;

// 历史上这个补丁重复插入过 titleHref，先收敛成一次，保证幂等
if (source.includes(DUP_TITLE)) {
    source = source.split(DUP_TITLE).join(PRELINK_TITLE_METHOD);
    changed += 1;
}

for (const [from, to] of REPLACEMENTS) {
    if (from === PRELINK_OWNER_PATTERN && source.includes(PRELINK_TITLE_METHOD)) {
        continue;
    }
    if (!source.includes(from)) {
        if (source.includes(to)) {
            console.log(`already patched: ${from.slice(0, 28)}…`);
            continue;
        }
        console.warn(`pattern not found (bundle changed?): ${from}`);
        continue;
    }
    source = source.split(from).join(to);
    changed += 1;
}

if (changed > 0) {
    writeFileSync(BUNDLE, source);
    console.log(`patched ${changed} pattern(s) in ${BUNDLE}`);
} else {
    console.log('nothing to patch');
}

// Logo 跳转补丁可能落在任意 chunk 里，这里全量扫一遍 frontend-dist/js。
{
    const JS_DIR = join(ROOT, 'frontend-dist', 'js');
    const LOGO_FROM = 'this.useConfigLink&&this.userConfig?.logoLink';
    const LOGO_TO = 'this.userConfig?.logoLink';
    let files = 0;
    for (const name of readdirSync(JS_DIR)) {
        if (!name.endsWith('.js')) continue;
        const file = join(JS_DIR, name);
        const text = readFileSync(file, 'utf8');
        if (!text.includes(LOGO_FROM)) continue;
        writeFileSync(file, text.split(LOGO_FROM).join(LOGO_TO));
        files += 1;
        console.log(`patched logo link in ${name}`);
    }
    if (files === 0) console.log('logo link patch: nothing to do');
}

// ---------------------------------------------------------------------------
// SPA 回退页：EdgeOne 静态层对不存在的路径（如 /dashboard、/adminLogin）返回 404，
// 而本项目的 catch-all 边缘函数会先接到这些请求。这里把构建好的 index.html 内联进
// 函数包，未命中业务路由的 GET 请求直接返回它，刷新后台页面就不会再 404。
// ---------------------------------------------------------------------------
const INDEX_HTML = join(ROOT, 'frontend-dist', 'index.html');
const SPA_MODULE = join(ROOT, 'deploy', 'edgeone', 'spa-index.js');

try {
    const html = readFileSync(INDEX_HTML, 'utf8');
    const body = `// AUTO-GENERATED by scripts/patch-frontend-edgeone.mjs — 内容来自 frontend-dist/index.html\n`
        + `export const SPA_INDEX_HTML = ${JSON.stringify(html)};\n`;
    const prev = (() => {
        try { return readFileSync(SPA_MODULE, 'utf8'); } catch { return ''; }
    })();
    if (prev !== body) {
        writeFileSync(SPA_MODULE, body);
        console.log(`generated ${SPA_MODULE}`);
    } else {
        console.log('spa-index.js up to date');
    }
} catch (err) {
    console.warn(`skip spa-index generation: ${err.message}`);
}
